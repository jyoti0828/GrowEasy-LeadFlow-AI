import { z } from 'zod';

export const crmStatusEnum = z.enum([
  'GOOD_LEAD_FOLLOW_UP',
  'DID_NOT_CONNECT',
  'BAD_LEAD',
  'SALE_DONE',
  ''
]).catch('');

export const dataSourceEnum = z.enum([
  'leads_on_demand',
  'meridian_tower',
  'eden_park',
  'varah_swamy',
  'sarjapur_plots',
  ''
]).catch('');

export const crmRecordSchema = z.object({
  created_at: z.string().catch(''),
  name: z.string().catch(''),
  email: z.string().catch(''),
  country_code: z.string().catch(''),
  mobile_without_country_code: z.string().catch(''),
  company: z.string().catch(''),
  city: z.string().catch(''),
  state: z.string().catch(''),
  country: z.string().catch(''),
  lead_owner: z.string().catch(''),
  crm_status: crmStatusEnum,
  crm_note: z.string().catch(''),
  data_source: dataSourceEnum,
  possession_time: z.string().catch(''),
  description: z.string().catch(''),
}).strip(); // This ensures extra fields generated by AI are stripped

export type CrmRecord = z.infer<typeof crmRecordSchema>;
